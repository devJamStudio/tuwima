function updateMap() {
    const svg = document.getElementById('overlaySvg');

    // Clear previous overlay content
    svg.innerHTML = '';

    // Set viewBox
    svg.setAttribute('viewBox', `0 0 ${kropkiMapping.dimensions.width} ${kropkiMapping.dimensions.height}`);

    // Add areas and dots using marked areas data
    addAreasAndDots(svg);
}

function addAreasAndDots(svg) {
    markedAreasData.forEach((markedArea, index) => {
        // Create polygon area (hidden by default)
        const polygon = document.createElementNS('http://www.w3.org/2000/svg', 'polygon');
        const points = markedArea.points.map(p => `${p.x},${p.y}`).join(' ');
        polygon.setAttribute('points', points);
        polygon.setAttribute('fill', getAreaColor(markedArea.type));
        polygon.setAttribute('opacity', '0');
        polygon.setAttribute('stroke', getAreaColor(markedArea.type));
        polygon.setAttribute('stroke-width', '2');
        polygon.setAttribute('class', 'area');
        polygon.setAttribute('data-type', `${markedArea.type}-area`);
        polygon.setAttribute('data-index', index);
        polygon.addEventListener('mouseenter', (e) => {
            e.stopPropagation();
        });
        polygon.addEventListener('mouseleave', (e) => {
            e.stopPropagation();
        });
        svg.appendChild(polygon);

        // Create dot (visible)
        const dotCircle = document.createElementNS('http://www.w3.org/2000/svg', 'circle');
        dotCircle.setAttribute('cx', markedArea.dot.x);
        dotCircle.setAttribute('cy', markedArea.dot.y);
        dotCircle.setAttribute('r', 8);
        dotCircle.setAttribute('fill', `rgb(${markedArea.dot.rgb.join(',')})`);
        dotCircle.setAttribute('stroke', 'white');
        dotCircle.setAttribute('stroke-width', 2);
        dotCircle.setAttribute('class', 'dot');
        dotCircle.setAttribute('data-type', `${markedArea.type}-dot`);
        dotCircle.setAttribute('data-index', index);
        dotCircle.addEventListener('mouseenter', (e) => {
            e.stopPropagation();
            polygon.classList.add('show');
            updateApartmentInfo(markedArea.id);
        });
        dotCircle.addEventListener('mouseleave', (e) => {
            e.stopPropagation();
            polygon.classList.remove('show');
        });
        dotCircle.addEventListener('click', (e) => {
            e.stopPropagation();
            updateApartmentInfo(markedArea.id);
        });
        svg.appendChild(dotCircle);
    });
}

function getAreaColor(type) {
    const colors = {
        green: 'var(--success-color)',
        orange: 'var(--warning-color)',
        red: 'var(--danger-color)'
    };
    return colors[type] || 'var(--success-color)';
}

function updateApartmentInfo(areaId) {
    // Find apartment data by area ID
    const apartmentNumber = Object.keys(apartmentMapping).find(key => apartmentMapping[key] === areaId);
    const apartment = apartmentsData.find(apt => apt.number === apartmentNumber);

    if (apartment) {
        document.getElementById('selected-apartment-number').textContent = apartment.number;
        document.getElementById('selected-apartment-rooms').textContent = apartment.rooms;
        document.getElementById('selected-apartment-area').innerHTML = apartment.area + '<span class="text-style-11">m²</span>';
        document.getElementById('selected-apartment-garden').innerHTML = apartment.garden_area + '<span class="text-style-11">m²</span>';

        // Update status image
        const statusImg = document.querySelector('.text-48');
        if (apartment.status === 'available') {
            statusImg.src = '<?php echo get_template_directory_uri(); ?>/html/images/dost_pne.png';
            statusImg.alt = 'Dostępne';
        } else if (apartment.status === 'reserved') {
            statusImg.src = '<?php echo get_template_directory_uri(); ?>/html/images/zarezerwowane.png';
            statusImg.alt = 'Zarezerwowane';
        } else if (apartment.status === 'sold') {
            statusImg.src = '<?php echo get_template_directory_uri(); ?>/html/images/sprzedane.png';
            statusImg.alt = 'Sprzedane';
        }
    }
}

function hideAllAreas() {
    const areas = document.querySelectorAll('.area');
    areas.forEach(area => {
        area.classList.remove('show');
    });
}

